// Builds web/static/vendor/mdx-runtime.bundle.js.
//
// Why this exists: the previous mdx-runtime.js imported React and @mdx-js/mdx straight
// from esm.sh. Those four imports fanned out to ~200 third-party requests on the very
// origin that holds the decryption key and the remembered passphrase, and they cannot
// work at all inside the render sandbox (`connect-src 'none'` blocks them). Bundling to
// a single committed classic script fixes both.
//
// Run with:  cd tools/mdx-bundle && npm install && npm run build
// The output is committed, so contributors never need to run this.
import { build } from "esbuild";
import { readFileSync, writeFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const outfile = join(here, "..", "..", "web", "static", "vendor", "mdx-runtime.bundle.js");

const pkg = JSON.parse(readFileSync(join(here, "package.json"), "utf8"));
const versions = Object.entries(pkg.dependencies)
  .map(([name, v]) => `${name}@${v}`)
  .join(", ");

await build({
  entryPoints: [join(here, "entry.mjs")],
  outfile,
  bundle: true,
  minify: true,
  // IIFE, not ESM: the sandbox allows `script-src 'unsafe-inline' blob:` only, so a
  // module script with bare imports could never resolve there. A classic script that
  // assigns a global is the only shape that works inlined.
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  // react-dom reads process.env.NODE_ENV; without this the bundle ships the dev build
  // (bigger, and it warns on every render).
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  logLevel: "info",
});

// Prepend provenance so the pinned versions are visible in the committed artifact and
// in the browser, not only in VERSIONS.md.
const banner =
  `/*! AgentGate MDX runtime bundle — ${versions}\n` +
  ` * Generated by tools/mdx-bundle (npm run build). Do not edit by hand.\n` +
  ` * Exposes globalThis.AgentGateMDXVendor = { React, createRoot, compile, run, jsxRuntime }.\n` +
  ` */\n`;
writeFileSync(outfile, banner + readFileSync(outfile, "utf8"));

const kb = Math.round(statSync(outfile).size / 1024);
console.log(`\nwrote web/static/vendor/mdx-runtime.bundle.js (${kb} KB) — ${versions}`);
console.log("Remember to update web/static/vendor/VERSIONS.md if the versions changed.");
