// Builds lazy-gated vendored bundles in web/static/vendor/ for AgentGate's
// artifact renderer, webapp built-ins, and doc math support.
//
// Every bundle is a classic IIFE script that attaches to globalThis, so it works
// inlined inside the opaque-origin srcdoc sandbox (`script-src 'unsafe-inline'
// 'unsafe-eval' blob:; connect-src 'none'`).
//
// React-consuming libraries (lucide-react, recharts) externalize react /
// react-dom to globalThis.React / globalThis.ReactDOM so all hooks run against
// the single React 18 instance provided by artifact-runtime.bundle.js.
import { build } from "esbuild";
import { readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const vendorDir = join(here, "..", "..", "web", "static", "vendor");
const pkg = JSON.parse(readFileSync(join(here, "package.json"), "utf8"));

// Plugin that redirects React imports in secondary bundles (lucide-react, recharts)
// to globalThis.React / globalThis.ReactDOM provided by artifact-runtime.bundle.js.
const sharedReactPlugin = {
  name: "shared-react-globals",
  setup(b) {
    b.onResolve({ filter: /^react$/ }, () => ({ path: "react", namespace: "ag-global" }));
    b.onResolve({ filter: /^react\/jsx-runtime$/ }, () => ({ path: "react/jsx-runtime", namespace: "ag-global" }));
    b.onResolve({ filter: /^react-dom$/ }, () => ({ path: "react-dom", namespace: "ag-global" }));
    b.onResolve({ filter: /^react-dom\/client$/ }, () => ({ path: "react-dom/client", namespace: "ag-global" }));
    b.onLoad({ filter: /.*/, namespace: "ag-global" }, (args) => {
      if (args.path === "react") {
        return { contents: "module.exports = globalThis.React;", loader: "js" };
      }
      if (args.path === "react/jsx-runtime") {
        return { contents: "module.exports = globalThis.AgentGateArtifactVendor.jsxRuntime;", loader: "js" };
      }
      if (args.path === "react-dom") {
        return { contents: "module.exports = globalThis.ReactDOM;", loader: "js" };
      }
      if (args.path === "react-dom/client") {
        return { contents: "module.exports = { createRoot: globalThis.AgentGateArtifactVendor.createRoot };", loader: "js" };
      }
      return null;
    });
  },
};

async function buildBundle({ name, code, bannerText, plugins = [] }) {
  const outfile = join(vendorDir, name);
  await build({
    stdin: {
      contents: code,
      resolveDir: here,
      loader: "js",
    },
    outfile,
    bundle: true,
    minify: true,
    format: "iife",
    platform: "browser",
    target: ["es2020"],
    define: { "process.env.NODE_ENV": '"production"' },
    legalComments: "none",
    plugins,
    logLevel: "warning",
  });
  const banner = `/*! AgentGate vendored bundle: ${name} — ${bannerText}\n * Generated by tools/artifact-bundle (npm run build). Do not edit by hand.\n */\n`;
  writeFileSync(outfile, banner + readFileSync(outfile, "utf8"));
  const kb = Math.round(statSync(outfile).size / 1024);
  console.log(`wrote web/static/vendor/${name} (${kb} KB)`);
}

// 1. Core Artifact Runtime: React 18 + ReactDOM + Sucrase JSX/TSX transpiler
await buildBundle({
  name: "artifact-runtime.bundle.js",
  bannerText: `react@${pkg.dependencies.react}, react-dom@${pkg.dependencies["react-dom"]}, sucrase@${pkg.dependencies.sucrase}`,
  code: `
    import React from "react";
    import * as ReactDOM from "react-dom";
    import { createRoot } from "react-dom/client";
    import * as jsxRuntime from "react/jsx-runtime";
    import { transform } from "sucrase";
    globalThis.React = React;
    globalThis.ReactDOM = ReactDOM;
    globalThis.AgentGateArtifactVendor = { React, ReactDOM, createRoot, jsxRuntime, transform };
  `,
});

// 2. Offline Tailwind utility CSS runtime (Twind v1 + Tailwind preset)
await buildBundle({
  name: "twind.bundle.js",
  bannerText: `@twind/core@${pkg.dependencies["@twind/core"]}, @twind/preset-tailwind@${pkg.dependencies["@twind/preset-tailwind"]}`,
  code: `
    import { install, tw } from "@twind/core";
    import presetAutoprefix from "@twind/preset-autoprefix";
    import presetTailwind from "@twind/preset-tailwind";
    function setupTwind() {
      try {
        install({
          presets: [presetAutoprefix(), presetTailwind()],
          darkMode: '[data-theme="dark"] &',
          hash: false,
        });
      } catch (e) {
        // Fallback if already installed
      }
    }
    if (typeof document !== "undefined") {
      setupTwind();
    }
    globalThis.AgentGateTwind = { install, tw, setup: setupTwind };
  `,
});

// 3. Lucide React icons (shares globalThis.React)
await buildBundle({
  name: "lucide-react.bundle.js",
  bannerText: `lucide-react@${pkg.dependencies["lucide-react"]}`,
  plugins: [sharedReactPlugin],
  code: `
    import * as LucideReact from "lucide-react";
    globalThis.LucideReact = LucideReact;
  `,
});

// 4. Chart.js (works in both vanilla HTML webapps and React artifacts)
await buildBundle({
  name: "chartjs.bundle.js",
  bannerText: `chart.js@${pkg.dependencies["chart.js"]}`,
  code: `
    import Chart from "chart.js/auto";
    globalThis.Chart = Chart;
  `,
});

// 5. Recharts (shares globalThis.React / globalThis.ReactDOM)
await buildBundle({
  name: "recharts.bundle.js",
  bannerText: `recharts@${pkg.dependencies.recharts}`,
  plugins: [sharedReactPlugin],
  code: `
    import * as Recharts from "recharts";
    globalThis.Recharts = Recharts;
  `,
});

// 6. KaTeX JS + self-contained CSS (woff2 fonts inlined as data: URIs for font-src data: CSP)
await buildBundle({
  name: "katex.bundle.js",
  bannerText: `katex@${pkg.dependencies.katex}`,
  code: `
    import katex from "katex";
    globalThis.katex = katex;
  `,
});

{
  const katexDist = join(here, "node_modules", "katex", "dist");
  let css = readFileSync(join(katexDist, "katex.min.css"), "utf8");
  // Keep only woff2 font sources and inline them as data:font/woff2;base64,...
  // Removing woff/ttf fallbacks cuts CSS size significantly while supporting every
  // modern browser and complying with the sandbox's `font-src data:` CSP.
  css = css.replace(
    /src:url\(fonts\/([^)]+\.woff2)\)\s*format\("woff2"\)(?:,url\(fonts\/[^)]+\)\s*format\("[^"]+"\))*/g,
    (whole, file) => {
      const fontPath = join(katexDist, "fonts", file);
      if (!existsSync(fontPath)) return whole;
      const b64 = readFileSync(fontPath).toString("base64");
      return `src:url(data:font/woff2;base64,${b64}) format("woff2")`;
    }
  );
  const outCss = join(vendorDir, "katex.min.css");
  const banner = `/*! AgentGate vendored KaTeX CSS (woff2 inlined) — katex@${pkg.dependencies.katex} */\n`;
  writeFileSync(outCss, banner + css);
  const kb = Math.round(statSync(outCss).size / 1024);
  console.log(`wrote web/static/vendor/katex.min.css (${kb} KB)`);
}
